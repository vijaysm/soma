"""Turn the MyST pages under docs/ into the flat Markdown of a GitHub wiki.

The pages under docs/ are the one source: Sphinx builds them for Read the Docs,
and this script writes the same pages as GitHub wiki pages.

    python3 docs/wiki/build_wiki.py --out <wiki clone>   # write the pages
    python3 docs/wiki/build_wiki.py --check              # convert, write nothing

The pages are those Sphinx builds: index.md and every page its toctrees reach,
recursively. Each page becomes <Title>.md, named by its first heading with
characters other than letters, digits and hyphens dropped and spaces made
hyphens (index.md becomes Home.md), and the heading itself is dropped, since a
wiki shows the page name as its title. The toctrees of index.md also give
_Sidebar.md.

What is rewritten:

- a link to another page, page.md or page.md#anchor, becomes Title or
  Title#anchor; the anchor must name a heading of that page;
- a link to any other file or directory of the repository becomes a link to it
  on GitHub (--repo-url, --branch); a link that resolves to nothing is an error;
- a toctree becomes a list of links to its pages, under its caption;
- a note or warning becomes a block quote starting **Note:** or **Warning:**;
- an include is replaced by the lines of the file it names (after
  :start-line:), its links taken relative to that file;
- math ($...$, $$...$$) is left as it is, which GitHub renders.

Any other directive or role ({name}`...`) is an error, so a page that uses one
must be taught here first. --check fails on any error; --out writes nothing
unless there are none. Each page written starts with a comment naming its
source; --out removes the pages with that comment it did not write this time,
and leaves every other file in the directory alone.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent
ROOT = DOCS.parent
MARKER = "<!-- Generated by docs/wiki/build_wiki.py from "
ADMONITIONS = {"note": "Note", "warning": "Warning"}

FENCE = re.compile(r"^(`{3,}|:{3,})(.*)$")
DIRECTIVE = re.compile(r"^\{([a-z-]+)\}\s*(.*)$")
OPTION = re.compile(r"^:([a-z-]+):\s*(.*)$")
CODE_SPAN = re.compile(r"(`+)(?:.+?)\1")
LINK = re.compile(r"(!?)\[([^\]]*)\]\(([^)\s]+)\)")
ROLE = re.compile(r"\{[a-z]+\}`")
HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")


class ConversionError(Exception):
    pass


def slugify(title: str) -> str:
    """The anchor of a heading, as MyST (myst_heading_anchors) and GitHub make it."""
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", title)  # a link's text only
    text = re.sub(r"\$[^$]*\$", "", text)  # MyST leaves math out of the slug
    text = text.replace("`", "").replace("*", "")
    return re.sub(r"[^\w\- ]", "", text.lower().replace(" ", "-"))


def unique(slug: str, seen: set[str]) -> str:
    s, i = slug, 1
    while s in seen:
        s, i = f"{slug}-{i}", i + 1
    seen.add(s)
    return s


def wiki_name(title: str) -> str:
    name = re.sub(r"[^A-Za-z0-9 -]", "", title).strip()
    return re.sub(r"[ -]+", "-", name)


@dataclass
class Line:
    text: str
    base: Path  # the directory its links are relative to
    code: bool = False  # inside a code block: left as it is


@dataclass
class Page:
    source: Path
    title: str = ""
    name: str = ""
    lines: list[Line] = field(default_factory=list)
    anchors: set[str] = field(default_factory=set)  # its headings' slugs
    toctrees: list[tuple[str, list[Path]]] = field(default_factory=list)


def rel(path: Path) -> str:
    try:
        return str(path.relative_to(ROOT))
    except ValueError:
        return str(path)


def read_lines(path: Path, start: int = 0) -> list[str]:
    if not path.is_file():
        raise ConversionError(f"{rel(path)}: no such file")
    return path.read_text(encoding="utf-8").splitlines()[start:]


def expand(path: Path, raw: list[str], page: Page, errors: list[str]) -> list[Line]:
    """The lines of a page with its directives expanded."""
    out: list[Line] = []
    base = path.parent
    i = 0
    while i < len(raw):
        line = raw[i]
        fence = FENCE.match(line)
        if not fence:
            out.append(Line(line, base))
            i += 1
            continue
        mark, rest = fence.group(1), fence.group(2)
        end = i + 1
        while end < len(raw) and raw[end].rstrip() != mark:
            end += 1
        body = raw[i + 1 : end]
        i = end + 1
        directive = DIRECTIVE.match(rest.strip())
        if not directive:  # a code block
            out.append(Line(line, base, code=True))
            out.extend(Line(b, base, code=True) for b in body)
            out.append(Line(mark, base, code=True))
            continue
        name, argument = directive.groups()
        options: dict[str, str] = {}
        while body and OPTION.match(body[0]):
            key, value = OPTION.match(body[0]).groups()
            options[key] = value
            body = body[1:]
        where = f"{rel(path)}: {{{name}}}"
        if name == "toctree":
            entries = [base / f"{b.strip()}.md" for b in body if b.strip()]
            page.toctrees.append((options.get("caption", ""), entries))
            out.append(Line(f"\0toctree {len(page.toctrees) - 1}", base))
        elif name in ADMONITIONS:
            inner = expand(path, body, page, errors)
            first = True
            for item in inner:
                text = item.text
                if first and not item.code and text.strip():
                    text, first = f"**{ADMONITIONS[name]}:** {text}", False
                out.append(Line(f"> {text}".rstrip(), item.base, item.code))
        elif name == "include":
            target = (base / argument).resolve()
            try:
                included = read_lines(target, int(options.get("start-line", "0")))
            except (ConversionError, ValueError) as e:
                errors.append(f"{where}: {e}")
                continue
            out.extend(expand(target, included, page, errors))
        else:
            errors.append(f"{where} is not supported; teach docs/wiki/build_wiki.py")
    return out


def load(path: Path, errors: list[str]) -> Page:
    page = Page(path.resolve())
    raw = read_lines(page.source)
    page.lines = expand(page.source, raw, page, errors)
    seen: set[str] = set()
    for line in page.lines:
        if line.code:
            continue
        heading = HEADING.match(line.text.lstrip("> ").rstrip())
        if not heading:
            continue
        if not page.title and len(heading.group(1)) == 1:
            page.title = heading.group(2)
        slug = slugify(heading.group(2))
        page.anchors.add(unique(slug, seen))
    if not page.title:
        errors.append(f"{rel(page.source)}: no '# Title' heading")
        page.title = page.source.stem
    return page


def collect(errors: list[str]) -> dict[Path, Page]:
    """index.md and every page its toctrees reach, in that order."""
    pages: dict[Path, Page] = {}
    todo = [DOCS / "index.md"]
    while todo:
        path = todo.pop(0).resolve()
        if path in pages:
            continue
        try:
            page = load(path, errors)
        except ConversionError as e:
            errors.append(str(e))
            continue
        pages[path] = page
        for _, entries in page.toctrees:
            todo.extend(entries)
    names: dict[str, Path] = {}
    for path, page in pages.items():
        page.name = "Home" if path == (DOCS / "index.md").resolve() else wiki_name(page.title)
        if page.name in names:
            errors.append(f"{rel(path)} and {rel(names[page.name])} would both be the wiki page {page.name}")
        names[page.name] = path
    return pages


class Renderer:
    def __init__(self, pages: dict[Path, Page], repo_url: str, branch: str, errors: list[str]):
        self.pages, self.repo_url, self.branch, self.errors = pages, repo_url.rstrip("/"), branch, errors

    def anchor(self, page: Page, slug: str, where: str) -> str:
        if slug not in page.anchors:
            self.errors.append(f"{where}: no heading #{slug} in {rel(page.source)}")
        return slug  # GitHub makes the same slug from the same heading

    def target(self, url: str, base: Path, page: Page, where: str) -> str:
        if re.match(r"^[a-z][a-z0-9+.-]*:", url):  # http:, https:, mailto:
            return url
        path_part, _, slug = url.partition("#")
        if not path_part:
            return f"#{self.anchor(page, slug, where)}"
        path = (base / path_part).resolve()
        if path in self.pages:
            other = self.pages[path]
            return other.name + (f"#{self.anchor(other, slug, where)}" if slug else "")
        if path.suffix == ".md" and path.is_relative_to(DOCS) and path.exists():
            self.errors.append(f"{where}: {path_part} is not in any toctree")
            return url
        if not path.exists() or not path.is_relative_to(ROOT):
            self.errors.append(f"{where}: {path_part} does not exist")
            return url
        kind = "tree" if path.is_dir() else "blob"
        return f"{self.repo_url}/{kind}/{self.branch}/{path.relative_to(ROOT).as_posix()}" + (
            f"#{slug}" if slug else ""
        )

    def links(self, text: str, base: Path, page: Page, where: str) -> str:
        def one(m: re.Match) -> str:
            bang, label, url = m.groups()
            return f"{bang}[{label}]({self.target(url, base, page, where)})"

        parts, last = [], 0
        for span in CODE_SPAN.finditer(text):  # code spans keep their brackets
            parts.append(LINK.sub(one, text[last : span.start()]))
            parts.append(span.group(0))
            last = span.end()
        parts.append(LINK.sub(one, text[last:]))
        out = "".join(parts)
        spans = [m.span() for m in CODE_SPAN.finditer(out)]
        if any(not any(a <= r.start() < b for a, b in spans) for r in ROLE.finditer(out)):
            self.errors.append(f"{where}: a {{role}}`...` is not supported; teach docs/wiki/build_wiki.py")
        return out

    def toctree(self, caption: str, entries: list[Path], where: str) -> list[str]:
        out = [f"## {caption}", ""] if caption else []
        for entry in entries:
            other = self.pages.get(entry.resolve())
            if other is None:
                self.errors.append(f"{where}: toctree entry {rel(entry)} was not converted")
                continue
            out.append(f"- [{other.title}]({other.name})")
        return out + [""]

    def page(self, page: Page) -> str:
        out = [f"{MARKER}{rel(page.source)}; edit that file, not this page. -->", ""]
        dropped_title = False
        for n, line in enumerate(page.lines, 1):
            where = f"{rel(page.source)}:{n}"
            if line.code:
                out.append(line.text)
            elif line.text.startswith("\0toctree "):
                caption, entries = page.toctrees[int(line.text.split()[1])]
                out.extend(self.toctree(caption, entries, where))
            elif not dropped_title and HEADING.match(line.text) and line.text.startswith("# "):
                dropped_title = True
            else:
                out.append(self.links(line.text, line.base, page, where))
        while len(out) > 2 and not out[2].strip():
            del out[2]
        return "\n".join(out).rstrip() + "\n"

    def sidebar(self, home: Page) -> str:
        out = [f"{MARKER}{rel(home.source)}; edit that file, not this page. -->", "", f"**[{home.title}](Home)**", ""]
        for caption, entries in home.toctrees:
            out += [f"**{caption}**", ""] if caption else []
            for entry in entries:
                other = self.pages.get(entry.resolve())
                if other is not None:
                    out.append(f"- [{other.title}]({other.name})")
            out.append("")
        return "\n".join(out).rstrip() + "\n"


def build(repo_url: str, branch: str) -> tuple[dict[str, str], list[str]]:
    errors: list[str] = []
    pages = collect(errors)
    renderer = Renderer(pages, repo_url, branch, errors)
    files = {f"{p.name}.md": renderer.page(p) for p in pages.values()}
    home = pages.get((DOCS / "index.md").resolve())
    if home is not None:
        files["_Sidebar.md"] = renderer.sidebar(home)
    return files, errors


def write(files: dict[str, str], out: Path) -> tuple[int, int]:
    out.mkdir(parents=True, exist_ok=True)
    removed = 0
    for old in sorted(out.glob("*.md")):
        if old.name not in files and old.read_text(encoding="utf-8").startswith(MARKER):
            old.unlink()
            removed += 1
    for name, text in sorted(files.items()):
        (out / name).write_text(text, encoding="utf-8")
    return len(files), removed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--out", type=Path, help="the wiki directory (a clone of <repo>.wiki.git) to write")
    mode.add_argument("--check", action="store_true", help="convert every page and write nothing")
    parser.add_argument("--repo-url", default="https://github.com/vijaysm/soma", help="for links to repository files")
    parser.add_argument("--branch", default="main", help="for links to repository files")
    args = parser.parse_args(argv)

    files, errors = build(args.repo_url, args.branch)
    if errors:
        for e in errors:
            print(f"build_wiki: {e}", file=sys.stderr)
        print(f"build_wiki: {len(errors)} error(s); nothing written", file=sys.stderr)
        return 1
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            written, _ = write(files, Path(tmp))
        print(f"build_wiki: {written} wiki pages convert cleanly")
        return 0
    written, removed = write(files, args.out)
    print(f"build_wiki: wrote {written} pages to {args.out}, removed {removed} stale")
    return 0


if __name__ == "__main__":
    sys.exit(main())
